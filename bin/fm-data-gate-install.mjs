#!/usr/bin/env node
// User-level installer for the data gate (bin/fm-data-gate.sh).
// bin/fm-data-gate-install.sh is the entry point and owns usage; this module
// owns the plan, the merge, the backups, the manifest, and the restore.
// docs/data-gate.md owns the operator contract.
//
// Every target is derived from $HOME and the account registries of the homes
// discovered under it, never from harness config-dir variables, so a test that
// sets HOME to a temporary directory can never reach the real settings. A
// harness target is planned only when that harness's user config directory
// already exists.
//
// Restore rule: uninstall writes back the exact pre-install bytes (or deletes a
// file install created) when the file still holds exactly what the first
// install wrote; if anything else changed it since, including between two
// installs, uninstall removes only the gate entries.

import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  realpathSync,
  renameSync,
  rmdirSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync, spawnSync } from "node:child_process";
import { DEFAULT_BULK, bulkEntries, discover, writeCache, stateDir, cachePath, logPath } from "./fm-data-gate-policy.mjs";

const MARK = "fm-data-gate.sh";
const BLOCK_BEGIN = "# lattice-data-gate BEGIN (generated by bin/fm-data-gate-install.sh; bulk dirs)";
const BLOCK_END = "# lattice-data-gate END";
const LEDGER_BULK = ["search-recording/", "diagnostics/"];
const REPORT_TIMER = "lattice-data-gate-report.timer";
const REPORT_UNITS = ["lattice-data-gate-report.service", REPORT_TIMER];

const home = () => process.env.HOME || "/";
const manifestPath = () => join(stateDir(), "install-manifest.json");
const sha = (text) => createHash("sha256").update(text).digest("hex");

function read(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

function isDir(path) {
  try {
    return statSync(path).isDirectory();
  } catch {
    return false;
  }
}

// ---------------------------------------------------------------------------
// Content builders.

function claudeCommand(gate) {
  return `[ -z "\${GROK_AGENT:-}\${GROK_HOOK_EVENT:-}" ] || exit 0; [ -x '${gate}' ] || exit 0; exec '${gate}' --harness claude`;
}

function codexCommand(gate) {
  return `[ -x '${gate}' ] || exit 0; exec '${gate}' --harness codex`;
}

function isGateHook(hook) {
  return typeof hook?.command === "string" && hook.command.includes(MARK);
}

// Remove every gate hook (and any group left empty by that) from a hooks
// settings object. Returns true when something was removed.
function stripJsonHooks(settings) {
  let removed = false;
  const events = settings?.hooks;
  if (!events || typeof events !== "object") return false;
  for (const event of Object.keys(events)) {
    if (!Array.isArray(events[event])) continue;
    const kept = [];
    for (const group of events[event]) {
      if (!Array.isArray(group?.hooks) || !group.hooks.some(isGateHook)) {
        kept.push(group);
        continue;
      }
      removed = true;
      const rest = group.hooks.filter((hook) => !isGateHook(hook));
      if (rest.length) kept.push({ ...group, hooks: rest });
    }
    if (kept.length) events[event] = kept;
    else delete events[event];
  }
  if (Object.keys(events).length === 0) delete settings.hooks;
  return removed;
}

// Put the gate entry where an earlier gate entry sat (else last), so keys and
// groups added around it since keep their order and a re-install stays a no-op.
function mergeJsonHook(text, matcher, command) {
  const settings = text === null || text.trim() === "" ? {} : JSON.parse(text);
  if (!settings || typeof settings !== "object" || Array.isArray(settings)) throw new Error("not a JSON object");
  settings.hooks ??= {};
  const entry = { matcher, hooks: [{ type: "command", command, timeout: 10 }] };
  const groups = [];
  let placed = false;
  for (const group of Array.isArray(settings.hooks.PreToolUse) ? settings.hooks.PreToolUse : []) {
    if (!Array.isArray(group?.hooks) || !group.hooks.some(isGateHook)) {
      groups.push(group);
      continue;
    }
    if (!placed) groups.push(entry);
    placed = true;
    const rest = group.hooks.filter((hook) => !isGateHook(hook));
    if (rest.length) groups.push({ ...group, hooks: rest });
  }
  if (!placed) groups.push(entry);
  settings.hooks.PreToolUse = groups;
  return `${JSON.stringify(settings, null, 2)}\n`;
}

// Codex's trust identity for one hook (codex-rs hooks discovery, hook_hash):
// sha256 of the canonical, key-sorted JSON of the normalized hook with its
// event, stored in config.toml as [hooks.state."<file>:<event>:<group>:<handler>"].
function codexGateTrust(hooksPath, hooksText) {
  const groups = JSON.parse(hooksText)?.hooks?.PreToolUse || [];
  const group = groups.findIndex((g) => Array.isArray(g?.hooks) && g.hooks.some(isGateHook));
  if (group === -1) return null;
  const handler = groups[group].hooks.findIndex(isGateHook);
  const hook = groups[group].hooks[handler];
  const identity = {
    event_name: "pre_tool_use",
    hooks: [{ async: false, command: hook.command, timeout: hook.timeout ?? 600, type: "command" }],
    ...(typeof groups[group].matcher === "string" ? { matcher: groups[group].matcher } : {}),
  };
  return { key: `${hooksPath}:pre_tool_use:${group}:${handler}`, hash: `sha256:${sha(JSON.stringify(identity))}` };
}

const tomlKey = (key) => `"${key.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

// Remove the [hooks.state."<key>"] tables whose only line is the given trusted
// hash (any hash when the trust names none).
function stripTrust(text, trusts) {
  const lines = text.split("\n");
  const out = [];
  for (let i = 0; i < lines.length; i += 1) {
    const trust = trusts.find((t) => lines[i].trim() === `[hooks.state.${tomlKey(t.key)}]`);
    if (trust) {
      let end = i + 1;
      while (end < lines.length && !lines[end].trim().startsWith("[")) end += 1;
      const body = lines.slice(i + 1, end).filter((line) => line.trim());
      const hash = body.length === 1 ? body[0].trim().match(/^trusted_hash = "([^"]*)"$/)?.[1] : undefined;
      if (hash !== undefined && (trust.hash === undefined || hash === trust.hash)) {
        while (out.length && out.at(-1).trim() === "") out.pop();
        if (end < lines.length) out.push("");
        i = end - 1;
        continue;
      }
    }
    out.push(lines[i]);
  }
  return out.join("\n");
}

function mergeTrust(text, trust, stale) {
  const current = text ?? "";
  const table = `[hooks.state.${tomlKey(trust.key)}]\ntrusted_hash = "${trust.hash}"\n`;
  const same = !stale || (stale.key === trust.key && stale.hash === trust.hash);
  if (same && stripTrust(current, [trust]) !== current) return current;
  const base = stripTrust(current, [{ key: trust.key }, ...(stale ? [stale] : [])]).replace(/\n*$/, "");
  if (base.includes(tomlKey(trust.key))) throw new Error(`an existing ${trust.key} entry has more than a trusted_hash`);
  return base ? `${base}\n\n${table}` : table;
}

// A unit template from bin/systemd/ with the report script and node's
// directory filled in; `%` is doubled because systemd reads it as a specifier.
function reportUnit(name, gate) {
  const values = { "@REPORT@": join(dirname(gate), "fm-data-gate-report.sh"), "@NODE_DIR@": dirname(process.execPath) };
  let text = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "systemd", name), "utf8");
  for (const [key, value] of Object.entries(values)) {
    if (/["\\\n]/.test(value)) throw new Error(`${value} has characters a unit file cannot carry`);
    text = text.replaceAll(key, value.replaceAll("%", "%%"));
  }
  return text;
}

function systemctl(args) {
  const result = spawnSync("systemctl", ["--user", ...args], { encoding: "utf8", timeout: 30000 });
  if (result.error) return result.error.code === "ENOENT" ? "systemctl not found" : result.error.message;
  return result.status === 0 ? null : (result.stderr || "").trim() || `exit ${result.status}`;
}

function grokHookFile(gate) {
  const hook = {
    hooks: {
      PreToolUse: [
        { matcher: "Bash", hooks: [{ type: "command", command: `bash -c '[ -x "${gate}" ] || exit 0; exec "${gate}" --harness grok'`, timeout: 10 }] },
      ],
    },
  };
  return `${JSON.stringify(hook, null, 2)}\n`;
}

function opencodePlugin(gate) {
  return `// Generated by bin/fm-data-gate-install.sh (${MARK}); uninstall removes it.
// User-level data gate for OpenCode: tool.execute.before blocks by throwing.
import { spawn } from "node:child_process";
import { existsSync } from "node:fs";

const GATE = ${JSON.stringify(gate)};

function run(args, cwd) {
  return new Promise((done) => {
    let child;
    try {
      child = spawn(GATE, args, { cwd, stdio: ["ignore", "ignore", "pipe"] });
    } catch {
      done({ code: 0, stderr: "" });
      return;
    }
    let stderr = "";
    child.stderr.on("data", (chunk) => { stderr += chunk.toString(); });
    child.on("error", () => done({ code: 0, stderr: "" }));
    child.on("close", (code) => done({ code: code ?? 0, stderr }));
  });
}

export const LatticeDataGate = async ({ directory }) => ({
  "tool.execute.before": async (input, output) => {
    if (!existsSync(GATE)) return;
    const tool = input?.tool;
    const a = output?.args || {};
    const cwd = directory || process.cwd();
    let args;
    if (tool === "bash" && typeof a.command === "string") args = ["--harness", "opencode", "--cwd", cwd, "--command", a.command];
    else if (tool === "grep" || tool === "glob") args = ["--harness", "opencode", "--cwd", cwd, "--tool", tool, "--path", a.path || "", "--pattern", a.pattern || ""];
    else if (tool === "read") args = ["--harness", "opencode", "--cwd", cwd, "--tool", "read", "--path", a.filePath || a.path || "", ...(a.offset != null ? ["--offset", String(a.offset)] : []), ...(a.limit != null ? ["--limit", String(a.limit)] : [])];
    else return;
    const result = await run(args, cwd);
    if (result.code === 2) throw new Error(result.stderr.trim() || "blocked by the data gate");
  },
});
`;
}

function piExtension(gate, harness) {
  return `// Generated by bin/fm-data-gate-install.sh (${MARK}); uninstall removes it.
// User-level data gate for ${harness}: a tool_call handler blocks by returning {block: true}.
import { spawn } from "node:child_process";
import { existsSync } from "node:fs";

const GATE = ${JSON.stringify(gate)};

function run(args: string[], cwd: string): Promise<{ code: number; stderr: string }> {
  return new Promise((done) => {
    let child: any;
    try {
      child = spawn(GATE, args, { cwd, stdio: ["ignore", "ignore", "pipe"] });
    } catch {
      done({ code: 0, stderr: "" });
      return;
    }
    let stderr = "";
    child.stderr?.on("data", (chunk: any) => { stderr += chunk.toString(); });
    child.on("error", () => done({ code: 0, stderr: "" }));
    child.on("close", (code: number | null) => done({ code: code ?? 0, stderr }));
  });
}

export default function (pi: any) {
  pi.on?.("tool_call", async (event: any, ctx: any) => {
    if (!event || event.type !== "tool_call" || !existsSync(GATE)) return {};
    const input = event.input || {};
    const cwd = typeof ctx?.cwd === "string" && ctx.cwd ? ctx.cwd : process.cwd();
    let args: string[];
    if (event.toolName === "bash" && typeof input.command === "string") {
      args = ["--harness", "${harness}", "--cwd", cwd, "--command", input.command];
    } else if (event.toolName === "grep" || event.toolName === "find") {
      args = ["--harness", "${harness}", "--cwd", cwd, "--tool", "grep", "--path", String(input.path || ""), "--pattern", String(input.pattern || "")];
    } else if (event.toolName === "read") {
      args = ["--harness", "${harness}", "--cwd", cwd, "--tool", "read", "--path", String(input.path || input.file_path || ""), ...(input.offset != null ? ["--offset", String(input.offset)] : []), ...(input.limit != null ? ["--limit", String(input.limit)] : [])];
    } else {
      return {};
    }
    const result = await run(args, cwd);
    if (result.code !== 2) return {};
    return { block: true, reason: result.stderr.trim() || "blocked by the data gate" };
  });
}
`;
}

function blockRange(text) {
  const start = text.indexOf(BLOCK_BEGIN);
  if (start === -1) return null;
  const endMark = text.indexOf(BLOCK_END, start);
  if (endMark === -1) return null;
  return { start, end: endMark + BLOCK_END.length + (text[endMark + BLOCK_END.length] === "\n" ? 1 : 0) };
}

function stripBlock(text) {
  const range = blockRange(text);
  return range ? text.slice(0, range.start) + text.slice(range.end) : text;
}

function mergeBlock(text, entries) {
  const current = text ?? "";
  const block = `${BLOCK_BEGIN}\n${entries.join("\n")}\n${BLOCK_END}\n`;
  const range = blockRange(current);
  if (range) return current.slice(0, range.start) + block + current.slice(range.end);
  return `${current}${current && !current.endsWith("\n") ? "\n" : ""}${block}`;
}

// Every Claude config dir: ~/.claude, ~/.claude-work, and every Claude login
// folder registered in a discovered home's config/accounts (bin/fm-account-lib.sh).
function claudeConfigDirs(homes) {
  const h = home();
  const dirs = [join(h, ".claude"), join(h, ".claude-work")];
  for (const fmHome of homes) {
    for (const raw of (read(join(fmHome, "config", "accounts")) || "").split("\n")) {
      const [name, provider, dir] = raw.replace(/#.*/, "").trim().split(/\s+/);
      if (!name || provider !== "claude" || !dir) continue;
      const expanded = dir === "~" ? h : dir.startsWith("~/") ? join(h, dir.slice(2)) : dir;
      if (isAbsolute(expanded)) dirs.push(expanded);
    }
  }
  const seen = new Set();
  return dirs.filter((dir) => {
    if (!isDir(dir)) return false;
    const real = realpathSync(dir);
    if (seen.has(real)) return false;
    seen.add(real);
    return true;
  });
}

// ---------------------------------------------------------------------------
// Plan.

function targets(gate) {
  const h = home();
  const plan = [];
  const roots = discover();
  for (const dir of claudeConfigDirs(roots.homes)) {
    plan.push({ path: join(dir, "settings.json"), kind: "json", label: `Claude PreToolUse Bash|Grep|Glob|Read`, build: (text) => mergeJsonHook(text, "Bash|Grep|Glob|Read", claudeCommand(gate)) });
  }
  if (isDir(join(h, ".codex"))) {
    const hooksPath = join(h, ".codex", "hooks.json");
    const merged = {};
    plan.push({
      path: hooksPath,
      kind: "json",
      label: "Codex PreToolUse Bash",
      build: (text) => {
        merged.stale = text === null ? null : codexGateTrust(hooksPath, text);
        merged.text = mergeJsonHook(text, "Bash", codexCommand(gate));
        return merged.text;
      },
    });
    plan.push({
      path: join(h, ".codex", "config.toml"),
      kind: "trust",
      label: "Codex trust for the gate hook",
      build: (text) => {
        if (merged.text === undefined) throw new Error("hooks.json was not merged");
        merged.trust = codexGateTrust(hooksPath, merged.text);
        return mergeTrust(text, merged.trust, merged.stale);
      },
      record: () => ({ trust: merged.trust }),
      trustOf: (hooksText) => codexGateTrust(hooksPath, hooksText),
      hooksPath,
    });
  }
  if (isDir(join(h, ".grok"))) plan.push({ path: join(h, ".grok", "hooks", "lattice-data-gate.json"), kind: "file", label: "Grok global PreToolUse hook", build: () => grokHookFile(gate) });
  if (isDir(join(h, ".config", "opencode"))) plan.push({ path: join(h, ".config", "opencode", "plugins", "lattice-data-gate.js"), kind: "file", label: "OpenCode global plugin", build: () => opencodePlugin(gate) });
  if (isDir(join(h, ".pi", "agent"))) plan.push({ path: join(h, ".pi", "agent", "extensions", "lattice-data-gate.ts"), kind: "file", label: "Pi global extension", build: () => piExtension(gate, "pi") });
  if (isDir(join(h, ".omp", "agent"))) plan.push({ path: join(h, ".omp", "agent", "extensions", "lattice-data-gate.ts"), kind: "file", label: "OMP global extension", build: () => piExtension(gate, "omp") });

  for (const fmHome of roots.homes) {
    const data = join(fmHome, "data");
    const bulkFile = join(data, "bulk-paths.txt");
    const entries = [];
    for (const line of bulkEntries(mergeBlock(read(bulkFile), DEFAULT_BULK))) {
      const rel = isAbsolute(line) ? relative(data, line) : line;
      const entry = rel.endsWith("/") ? rel : `${rel}/`;
      if (rel && !rel.startsWith("..") && !entries.includes(entry)) entries.push(entry);
    }
    plan.push({ path: bulkFile, kind: "block", label: "generated bulk paths", build: (text) => mergeBlock(text, DEFAULT_BULK) });
    for (const name of [".ignore", ".rgignore"]) plan.push({ path: join(data, name), kind: "block", label: "bulk ignore list", build: (text) => mergeBlock(text, entries) });
  }
  const ledger = join(h, "lattice-ledger");
  if (isDir(ledger)) {
    for (const name of [".ignore", ".rgignore"]) plan.push({ path: join(ledger, name), kind: "block", label: "bulk ignore list", build: (text) => mergeBlock(text, LEDGER_BULK) });
  }
  for (const name of REPORT_UNITS) plan.push({ path: join(h, ".config", "systemd", "user", name), kind: "file", label: `daily report ${name.split(".").pop()}`, build: () => reportUnit(name, gate) });
  const modeFile = join(h, ".config", "lattice-data-gate", "mode");
  if (!existsSync(modeFile)) plan.push({ path: modeFile, kind: "file", label: "gate modes (scan log, size log)", build: () => "log\nsize log\n" });
  return { plan, roots };
}

function loadManifest() {
  const text = read(manifestPath());
  if (!text) return { files: {}, dirs: [] };
  const manifest = JSON.parse(text);
  manifest.files ??= {};
  manifest.dirs ??= [];
  return manifest;
}

function saveManifest(manifest) {
  mkdirSync(stateDir(), { recursive: true });
  const tmp = `${manifestPath()}.tmp.${process.pid}`;
  writeFileSync(tmp, `${JSON.stringify(manifest, null, 2)}\n`);
  renameSync(tmp, manifestPath());
}

function writeAtomic(path, text) {
  const tmp = `${path}.lattice-data-gate.tmp.${process.pid}`;
  writeFileSync(tmp, text);
  renameSync(tmp, path);
}

function mkdirTracked(dir, manifest, dryRun) {
  const created = [];
  let current = dir;
  while (!existsSync(current)) {
    created.unshift(current);
    current = dirname(current);
  }
  if (!dryRun) {
    for (const d of created) {
      mkdirSync(d);
      if (!manifest.dirs.includes(d)) manifest.dirs.push(d);
    }
  }
}

function stamp() {
  return new Date().toISOString().replace(/[:.]/g, "-");
}

// ---------------------------------------------------------------------------
// Commands.

function install({ dryRun, gate }) {
  const { plan } = targets(gate);
  const manifest = loadManifest();
  const backupDir = join(stateDir(), "backups", stamp());
  const lines = [];
  for (const item of plan) {
    const current = read(item.path);
    let next;
    try {
      next = item.build(current);
    } catch (error) {
      lines.push(`skipped   ${item.path}: cannot merge (${error.message}); left untouched`);
      continue;
    }
    if (current === next) {
      lines.push(`unchanged ${item.path} (${item.label} already present)`);
      continue;
    }
    let backup = null;
    if (current !== null) {
      const rel = relative(home(), item.path);
      backup = join(backupDir, rel.startsWith("..") ? join("root", relative("/", item.path)) : join("home", rel));
      if (!dryRun) {
        mkdirSync(dirname(backup), { recursive: true });
        copyFileSync(item.path, backup);
      }
    }
    if (!dryRun) {
      mkdirTracked(dirname(item.path), manifest, false);
      writeAtomic(item.path, next);
      const prior = manifest.files[item.path];
      manifest.files[item.path] = {
        kind: item.kind,
        existed: prior ? prior.existed : current !== null,
        original_backup: prior ? prior.original_backup : backup,
        installed_sha256: sha(next),
        strip_only: Boolean(prior && (prior.strip_only || sha(current ?? "") !== prior.installed_sha256)),
        ...(item.record ? item.record() : {}),
      };
    }
    const verb = current === null ? "created" : "changed";
    lines.push(`${verb.padEnd(9)} ${item.path} (+${item.label}${backup ? `; backup ${backup}` : ""})`);
  }
  const roots = discover();
  if (!dryRun) {
    saveManifest(manifest);
    writeCache(roots);
  }
  if (dryRun) lines.push(`would enable ${REPORT_TIMER}`);
  else {
    const failed = systemctl(["daemon-reload"]) || systemctl(["enable", "--now", REPORT_TIMER]);
    lines.push(failed ? `not enabled ${REPORT_TIMER} (${failed}); run: systemctl --user daemon-reload && systemctl --user enable --now ${REPORT_TIMER}` : `enabled ${REPORT_TIMER}`);
  }
  lines.push(`${dryRun ? "would refresh" : "refreshed"} roots cache ${cachePath()} (homes=${roots.homes.length}, bulk=${roots.bulk.length})`);
  lines.push(`gate ${gate}; mode after install: scan and size rules log unless ~/.config/lattice-data-gate/mode, LATTICE_DATA_GATE or LATTICE_DATA_GATE_SIZE says otherwise`);
  if (dryRun) lines.unshift("dry run: nothing was written");
  return lines;
}

function stripFile(entry, text) {
  if (entry.kind === "json") {
    const settings = JSON.parse(text);
    stripJsonHooks(settings);
    return `${JSON.stringify(settings, null, 2)}\n`;
  }
  if (entry.kind === "block") return stripBlock(text);
  if (entry.kind === "trust") return entry.trust ? stripTrust(text, [entry.trust]) : text;
  return null;
}

function uninstall({ dryRun }) {
  const manifest = loadManifest();
  const lines = [];
  const timer = Object.keys(manifest.files).some((path) => basename(path) === REPORT_TIMER);
  if (timer && !dryRun) systemctl(["disable", "--now", REPORT_TIMER]);
  for (const [path, entry] of Object.entries(manifest.files)) {
    const current = read(path);
    if (current === null) {
      lines.push(`gone      ${path} (already absent)`);
      delete manifest.files[path];
      continue;
    }
    if (!entry.strip_only && sha(current) === entry.installed_sha256) {
      if (entry.existed) {
        if (!dryRun) copyFileSync(entry.original_backup, path);
        lines.push(`restored  ${path} (exact pre-install bytes from ${entry.original_backup})`);
      } else {
        if (!dryRun) unlinkSync(path);
        lines.push(`removed   ${path} (created by install)`);
      }
    } else {
      let stripped;
      try {
        stripped = stripFile(entry, current);
      } catch (error) {
        lines.push(`skipped   ${path}: changed since install and cannot be parsed (${error.message}); left untouched`);
        continue;
      }
      if (stripped === null) {
        lines.push(`kept      ${path}: changed since install; remove it by hand if it is no longer wanted`);
        continue;
      }
      const empty = entry.kind === "block" && stripped === "" && !entry.existed;
      if (!dryRun) {
        if (empty) unlinkSync(path);
        else writeAtomic(path, stripped);
      }
      lines.push(`${empty ? "removed  " : "stripped "} ${path} (changed since install; removed only the gate entries)`);
    }
    if (!dryRun) delete manifest.files[path];
  }
  if (!dryRun) {
    for (const dir of [...manifest.dirs].reverse()) {
      try {
        if (readdirSync(dir).length === 0) rmdirSync(dir);
      } catch {
        // already gone or not empty: leave it
      }
    }
    manifest.dirs = [];
    if (timer) systemctl(["daemon-reload"]);
    for (const path of [manifestPath(), cachePath()]) {
      try {
        unlinkSync(path);
      } catch {
        // absent
      }
    }
  }
  if (lines.length === 0) lines.push("nothing installed (no manifest entries)");
  lines.push(`decision log kept: ${logPath()}`);
  if (dryRun) lines.unshift("dry run: nothing was written");
  return lines;
}

// One answer from the gate's own mode resolution (bin/fm-data-gate.sh owns it).
function gateQuery(gate, ...args) {
  try {
    return execFileSync(gate, args, { encoding: "utf8", timeout: 5000, stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

function status({ gate }) {
  const { plan, roots } = targets(gate);
  const manifest = loadManifest();
  const lines = [];
  const mode = (process.env.LATTICE_DATA_GATE || (read(join(home(), ".config", "lattice-data-gate", "mode")) || "").trim().split(/\s+/)[0] || "log");
  lines.push(`mode      ${mode === "enforce" ? mode : "log"}`);
  lines.push(`size      ${gateQuery(gate, "mode", "size") || "(unknown)"}, limit ${gateQuery(gate, "size-limit") || "(unknown)"} bytes`);
  lines.push(`gate      ${gate}`);
  const log = read(logPath());
  const records = log ? log.split("\n").filter(Boolean) : [];
  lines.push(`log       ${logPath()} (${records.length} records, ${records.filter((r) => r.includes('"would_block":true')).length} would-block)`);
  lines.push(`roots     homes=${roots.homes.length} bulk=${roots.bulk.length} cache=${existsSync(cachePath()) ? cachePath() : "(absent)"}`);
  for (const item of plan) {
    const text = read(item.path);
    let installed = false;
    if (text !== null) {
      if (item.kind === "json") installed = text.includes(MARK);
      else if (item.kind === "block") installed = text.includes(BLOCK_BEGIN);
      else if (item.kind === "trust") {
        let trust = null;
        try {
          trust = item.trustOf(read(item.hooksPath) ?? "{}");
        } catch {
          // an unparseable hooks.json has no gate hook to trust
        }
        installed = Boolean(trust) && stripTrust(text, [trust]) !== text;
      } else installed = Boolean(manifest.files[item.path]) || text === item.build(text);
    }
    lines.push(`${installed ? "installed" : "missing  "} ${item.path} (${item.label})`);
  }
  return lines;
}

function parse(argv) {
  const args = { sub: argv[0] || "", dryRun: false, gate: resolve(dirname(fileURLToPath(import.meta.url)), "fm-data-gate.sh") };
  for (let i = 1; i < argv.length; i += 1) {
    if (argv[i] === "--dry-run") args.dryRun = true;
    else if (argv[i] === "--gate") {
      args.gate = resolve(argv[i + 1] || "");
      i += 1;
    } else throw new Error(`unknown argument: ${argv[i]}`);
  }
  if (/['"\\$`]/.test(args.gate)) throw new Error(`gate path must not contain quotes, backslashes, $ or backticks: ${args.gate}`);
  return args;
}

try {
  const args = parse(process.argv.slice(2));
  let lines;
  if (args.sub === "install") lines = install(args);
  else if (args.sub === "uninstall") lines = uninstall(args);
  else if (args.sub === "status") lines = status(args);
  else throw new Error(`unknown subcommand: ${args.sub || "(none)"}; expected install|uninstall|status`);
  process.stdout.write(`${lines.join("\n")}\n`);
} catch (error) {
  process.stderr.write(`fm-data-gate-install: ${error.message}\n`);
  process.exitCode = 1;
}
